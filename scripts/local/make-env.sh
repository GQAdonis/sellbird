#!/usr/bin/env bash
# Prepare a FRESH local stand-in run: credentials, keys, Kratos identities and
# aal2 session cookies, all in uncommitted files under infra/local/.
#
#   scripts/local/make-env.sh && docker compose -f infra/local/compose.yaml up -d --wait
#
# What it does, in order:
#   1. `docker compose down -v` on the stand-in (its own containers and volumes
#      only), because Postgres reads its passwords only when the volume is first
#      created, and every run gets new ones.
#   2. Generates random passwords (Postgres superuser, sellbird_migrate,
#      sellbird_app, kratos, flintgate, the two identities), Kratos cookie and
#      cipher secrets, and a 3072-bit RS256 key pair for flint-gate.
#   3. Renders flint-gate's config: infra/local/flint-gate/base.yaml merged with
#      infra/flint-gate/sellbird-routes.yaml (unmodified).
#   4. Writes infra/local/.env (mode 600) and starts only postgres, kratos and
#      flint-gate, health-gated.
#   5. Creates operator@example.test and other@example.test through the Kratos
#      admin API (inside the compose network; infra/kratos/create-identities.sh).
#   6. For each identity, through flint-gate's auth-host passthrough
#      (http://127.0.0.1:4456, Host auth.example.test), runs Kratos's browser
#      flows: password login, TOTP enrolment in the settings flow, then an aal2
#      TOTP login (scripts/local/kratos_session.py). The resulting
#      `ory_kratos_session` cookies are aal2.
#   7. Rewrites infra/local/.env with the operator's identity id as
#      SELLBIRD_GATE_ALLOWED_SUBS and the SELLBIRD_E2E_* variables. The services
#      already running do not read anything that changed, so the following
#      `docker compose up -d --wait` only adds sellbird-migrate and sellbird.
#
# Nothing secret is printed. Requires: docker (Compose v2), openssl, python3,
# and Sellbird's .venv (for PyYAML) or a python3 with PyYAML.
# Environment overrides: SELLBIRD_LOCAL_PG_PORT (default 55432),
# SELLBIRD_LOCAL_DIRECT_PORT (default 5555).
set -euo pipefail
# shellcheck source=scripts/local/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
umask 077

GATE_PORT=4456
GATE_KID=sellbird-local-rs256
GATE_ISSUER=https://gate.example.test
PUBLIC_HOST=sellbird.example.test
AUTH_HOST=auth.example.test
PG_PORT="${SELLBIRD_LOCAL_PG_PORT:-55432}"
DIRECT_PORT="${SELLBIRD_LOCAL_DIRECT_PORT:-5555}"
PLACEHOLDER_SUB=00000000-0000-4000-8000-000000000001

for tool in docker openssl python3; do
  command -v "$tool" >/dev/null || sb_die "$tool is required"
done
PY="$(sb_python)"
[[ "$PG_PORT" =~ ^[0-9]+$ && "$DIRECT_PORT" =~ ^[0-9]+$ ]] || sb_die "ports must be numeric"

rand_hex() { openssl rand -hex "$1"; }

# --- 1. fresh state -----------------------------------------------------------
echo "make-env: removing any previous stand-in containers and volumes"
# By project name, so it works even when a previous .env is missing (the
# compose file's required variables would otherwise stop `down`).
docker compose -p sellbird-local down -v --remove-orphans >/dev/null 2>&1 || true
if docker volume inspect sellbird-local_pg-data >/dev/null 2>&1; then
  sb_die "volume sellbird-local_pg-data still exists; remove it (docker volume rm) and rerun"
fi
rm -rf "$SB_GEN"
mkdir -p "$SB_GEN/kratos" "$SB_GEN/gate-keys"
chmod 700 "$SB_GEN" "$SB_GEN/kratos" "$SB_GEN/gate-keys"

# --- 2. secrets and keys ------------------------------------------------------
POSTGRES_SUPERUSER_PASSWORD="$(rand_hex 24)"
SELLBIRD_MIGRATE_PASSWORD="$(rand_hex 24)"
SELLBIRD_APP_PASSWORD="$(rand_hex 24)"
KRATOS_DB_PASSWORD="$(rand_hex 24)"
FLINTGATE_DB_PASSWORD="$(rand_hex 24)"
SELLBIRD_LOCAL_OPERATOR_PASSWORD="$(rand_hex 24)"
SELLBIRD_LOCAL_OTHER_PASSWORD="$(rand_hex 24)"

# PKCS#8 private key (what flint-gate's RS256 loader and PyJWT both accept)
# and its SPKI public key, which --database-init-only publishes in the JWKS.
openssl genrsa 3072 2>/dev/null \
  | openssl pkcs8 -topk8 -nocrypt -out "$SB_GEN/gate-keys/private.pem"
openssl rsa -in "$SB_GEN/gate-keys/private.pem" -pubout \
  -out "$SB_GEN/gate-keys/public.pem" 2>/dev/null
chmod 600 "$SB_GEN/gate-keys/private.pem" "$SB_GEN/gate-keys/public.pem"

# Kratos secrets as a second config file (cipher secrets must be 32 characters).
cat > "$SB_GEN/kratos/kratos-secrets.yml" <<EOF
# Generated by scripts/local/make-env.sh. Do not edit or commit.
secrets:
  default:
    - $(rand_hex 32)
  cookie:
    - $(rand_hex 32)
  cipher:
    - $(rand_hex 16)
EOF

# --- 3. flint-gate config -----------------------------------------------------
"$PY" -I "$SB_ROOT/scripts/local/render_gate_config.py" \
  "$SB_LOCAL/flint-gate/base.yaml" \
  "$SB_ROOT/infra/flint-gate/sellbird-routes.yaml" \
  "$SB_GEN/flint-gate.yaml"
chmod 644 "$SB_GEN/flint-gate.yaml"

# --- 4. .env and the platform services ----------------------------------------
# write_env ALLOWED_SUB OPERATOR_COOKIE OTHER_COOKIE: (re)write infra/local/.env
# atomically. Single quotes keep compose from interpolating cookie values.
write_env() {
  local tmp="$SB_ENV_FILE.tmp"
  cat > "$tmp" <<EOF
# Generated by scripts/local/make-env.sh for the local stand-in. Never commit.
# Regenerate with scripts/local/make-env.sh (it also resets the stand-in).
LOCAL_UID=$(id -u)
LOCAL_GID=$(id -g)
SELLBIRD_LOCAL_PG_PORT=$PG_PORT
SELLBIRD_LOCAL_DIRECT_PORT=$DIRECT_PORT
POSTGRES_SUPERUSER_PASSWORD=$POSTGRES_SUPERUSER_PASSWORD
SELLBIRD_MIGRATE_PASSWORD=$SELLBIRD_MIGRATE_PASSWORD
SELLBIRD_APP_PASSWORD=$SELLBIRD_APP_PASSWORD
KRATOS_DB_PASSWORD=$KRATOS_DB_PASSWORD
FLINTGATE_DB_PASSWORD=$FLINTGATE_DB_PASSWORD
SELLBIRD_LOCAL_OPERATOR_PASSWORD=$SELLBIRD_LOCAL_OPERATOR_PASSWORD
SELLBIRD_LOCAL_OTHER_PASSWORD=$SELLBIRD_LOCAL_OTHER_PASSWORD
SELLBIRD_GATE_ALLOWED_SUBS=$1
SELLBIRD_E2E_HOST=$PUBLIC_HOST
SELLBIRD_E2E_ALLOWED_SUB=$1
SELLBIRD_E2E_SESSION_COOKIE='$2'
SELLBIRD_E2E_OTHER_SESSION_COOKIE='$3'
SELLBIRD_E2E_DIRECT_URL=http://127.0.0.1:$DIRECT_PORT
SELLBIRD_E2E_PUBLIC_HOST=$PUBLIC_HOST
SELLBIRD_E2E_GATE_KEY_FILE='$SB_GEN/gate-keys/private.pem'
SELLBIRD_E2E_GATE_KID=$GATE_KID
SELLBIRD_E2E_GATE_ISSUER=$GATE_ISSUER
EOF
  chmod 600 "$tmp"
  mv "$tmp" "$SB_ENV_FILE"
}

write_env "$PLACEHOLDER_SUB" pending pending

echo "make-env: starting postgres, kratos and flint-gate (health-gated)"
"${SB_COMPOSE[@]}" up -d --wait postgres kratos flint-gate

# --- 5. identities ------------------------------------------------------------
echo "make-env: creating the operator and a non-allowlisted identity in Kratos"
ids="$(SELLBIRD_LOCAL_OPERATOR_PASSWORD="$SELLBIRD_LOCAL_OPERATOR_PASSWORD" \
       SELLBIRD_LOCAL_OTHER_PASSWORD="$SELLBIRD_LOCAL_OTHER_PASSWORD" \
       PYTHON=python3 "$SB_ROOT/infra/kratos/create-identities.sh")"
operator_id="$(printf '%s\n' "$ids" | sed -n 's/^OPERATOR_ID=//p')"
other_id="$(printf '%s\n' "$ids" | sed -n 's/^OTHER_ID=//p')"
uuid_re='^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
[[ "$operator_id" =~ $uuid_re && "$other_id" =~ $uuid_re ]] \
  || sb_die "Kratos did not return two identity ids"
[[ "$operator_id" != "$other_id" ]] || sb_die "identity ids are not distinct"

# --- 6. aal2 session cookies --------------------------------------------------
# session_cookie EMAIL PASSWORD: the aal2 Cookie header value on stdout.
session_cookie() {
  KRATOS_PUBLIC_URL="http://127.0.0.1:$GATE_PORT" KRATOS_HOST_HEADER="$AUTH_HOST" \
  KRATOS_EMAIL="$1" KRATOS_PASSWORD="$2" \
    python3 -I "$SB_ROOT/scripts/local/kratos_session.py"
}
cookie_re="^ory_kratos_session=[A-Za-z0-9._~+/=-]+$"

echo "make-env: signing in both identities with password + TOTP (about a minute)"
operator_cookie="$(session_cookie operator@example.test "$SELLBIRD_LOCAL_OPERATOR_PASSWORD")"
other_cookie="$(session_cookie other@example.test "$SELLBIRD_LOCAL_OTHER_PASSWORD")"
[[ "$operator_cookie" =~ $cookie_re && "$other_cookie" =~ $cookie_re ]] \
  || sb_die "Kratos returned an unexpected session cookie shape"

# --- 7. final .env ------------------------------------------------------------
write_env "$operator_id" "$operator_cookie" "$other_cookie"

cat <<EOF
make-env: ready. Wrote infra/local/.env and infra/local/.env.generated/ (uncommitted).
  next:  docker compose -f infra/local/compose.yaml up -d --wait
  DSNs:  scripts/local/dsn.sh migrate|app
  e2e:   SELLBIRD_GATEWAY_URL=http://localhost:$GATE_PORT \\
           scripts/local/e2e-env.sh .venv/bin/python -m pytest -q tests/test_gateway_mode_e2e.py
  clean: docker compose -f infra/local/compose.yaml down -v
EOF
