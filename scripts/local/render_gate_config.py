"""Merge the local flint-gate base config with Sellbird's route file.

Usage: python -I scripts/local/render_gate_config.py BASE ROUTES OUT

``sites`` and ``routes`` become BASE's lists followed by ROUTES' lists; every
other key comes from BASE. ROUTES may contain only ``sites`` and ``routes``
(it is the contract-owned file, infra/flint-gate/sellbird-routes.yaml), and a
duplicate site or route id is refused, so the route file is used unmodified.
Needs PyYAML (Sellbird's own dependency, present in its .venv).
"""

from __future__ import annotations

import os
import sys

try:
    import yaml
except ImportError:  # pragma: no cover - environment check
    sys.exit("render_gate_config: PyYAML is required (use Sellbird's .venv python)")


def _load(path: str) -> dict:
    with open(path, encoding="utf-8") as handle:
        data = yaml.safe_load(handle) or {}
    if not isinstance(data, dict):
        sys.exit(f"render_gate_config: {path} is not a mapping")
    return data


def merge(base: dict, routes: dict) -> dict:
    extra = set(routes) - {"sites", "routes"}
    if extra:
        sys.exit(f"render_gate_config: route file has non-route keys: {sorted(extra)}")
    merged = dict(base)
    for key in ("sites", "routes"):
        combined = list(base.get(key) or []) + list(routes.get(key) or [])
        ids = [item.get("id") for item in combined]
        if len(ids) != len(set(ids)) or None in ids:
            sys.exit(f"render_gate_config: duplicate or missing {key} id")
        merged[key] = combined
    return merged


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    _, base_path, routes_path, out_path = argv
    merged = merge(_load(base_path), _load(routes_path))
    tmp = out_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write("# Generated by scripts/local/make-env.sh. Do not edit or commit.\n")
        yaml.safe_dump(merged, handle, sort_keys=False)
    os.replace(tmp, out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
