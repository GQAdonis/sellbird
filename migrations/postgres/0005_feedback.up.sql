-- Comments people leave on any entity from the dashboard. The dashboard used
-- to create this table itself on first use; on both backends it now comes only
-- from migrations (SQLite: its migration 1), so the app needs no DDL rights.

CREATE TABLE feedback (
    id text COLLATE "C" PRIMARY KEY,
    entity_type text COLLATE "C" DEFAULT '',
    entity_id text COLLATE "C" DEFAULT '',
    comment text COLLATE "C" DEFAULT '',
    created_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_feedback_entity ON feedback (entity_type, entity_id);
