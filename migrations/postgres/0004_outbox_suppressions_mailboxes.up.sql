-- Sending: the outbox (approval ladder and double-send guard), suppressions
-- (never emailed, whoever asks) and the sending inboxes.
--
-- Outbox status ladder: pending_review -> approved -> sending -> sent, or
-- rejected / cancelled / failed. The partial unique index on
-- (campaign_id, prospect_id, step) is the double-send guard: a retried or
-- re-staged sequence email physically cannot become a second row.
-- Claiming an approved item for sending is one conditional UPDATE
-- (status = 'approved' -> 'sending'); under concurrent senders Postgres locks
-- the row and re-checks the condition, so exactly one claim succeeds.

CREATE TABLE outbox (
    id text COLLATE "C" PRIMARY KEY,
    campaign_id text COLLATE "C" DEFAULT '',
    prospect_id text COLLATE "C" DEFAULT '',
    conversation_id text COLLATE "C" DEFAULT '',
    step bigint DEFAULT 1,
    kind text COLLATE "C" DEFAULT 'sequence',
    to_email text COLLATE "C" DEFAULT '',
    subject text COLLATE "C" DEFAULT '',
    body text COLLATE "C" DEFAULT '',
    status text COLLATE "C" DEFAULT 'pending_review',
    send_at text COLLATE "C",
    sent_at text COLLATE "C",
    provider text COLLATE "C" DEFAULT '',
    message_id text COLLATE "C" DEFAULT '',
    thread_ref text COLLATE "C" DEFAULT '',
    in_reply_to text COLLATE "C" DEFAULT '',
    error text COLLATE "C" DEFAULT '',
    created_at text COLLATE "C" DEFAULT sb_now(),
    updated_at text COLLATE "C" DEFAULT sb_now(),
    approved_by text COLLATE "C" DEFAULT '',
    mailbox_id text COLLATE "C" DEFAULT '',
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
COMMENT ON TABLE outbox IS
    'Every outgoing email. pending_review -> approved -> sending -> sent; claimed exactly once.';
CREATE UNIQUE INDEX uq_outbox_campaign_step
    ON outbox (campaign_id, prospect_id, step)
    WHERE campaign_id <> '' AND kind = 'sequence';
CREATE INDEX idx_outbox_status_send_at ON outbox (status, send_at);
CREATE INDEX idx_outbox_prospect ON outbox (prospect_id);
CREATE INDEX idx_outbox_mailbox_sent ON outbox (mailbox_id, status, sent_at);

CREATE TABLE suppressions (
    id text COLLATE "C" PRIMARY KEY,
    kind text COLLATE "C" NOT NULL,
    value text COLLATE "C" NOT NULL,
    reason text COLLATE "C" DEFAULT 'manual',
    source text COLLATE "C" DEFAULT '',
    created_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
COMMENT ON TABLE suppressions IS
    'Addresses and domains never emailed (a domain covers its subdomains). Only the user removes one.';
CREATE UNIQUE INDEX uq_suppressions_kind_value ON suppressions (kind, value);

CREATE TABLE mailboxes (
    id text COLLATE "C" PRIMARY KEY,
    address text COLLATE "C" NOT NULL,
    display_name text COLLATE "C" DEFAULT '',
    provider text COLLATE "C" NOT NULL,
    connection text COLLATE "C" NOT NULL,
    state text COLLATE "C" DEFAULT 'active',
    paused_reason text COLLATE "C" DEFAULT '',
    cap_override bigint,
    credential_ref text COLLATE "C" DEFAULT '',
    settings_json text COLLATE "C" DEFAULT '{}',
    warmup_started_at text COLLATE "C",
    created_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT mailboxes_address_key UNIQUE (address)
);

CREATE TABLE campaign_mailboxes (
    campaign_id text COLLATE "C" NOT NULL,
    mailbox_id text COLLATE "C" NOT NULL,
    rowid bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (campaign_id, mailbox_id)
);
