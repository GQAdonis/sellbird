-- The observation model: every fact is a row, never a column.
--
-- signal_codes is the governed vocabulary. `status` is the human gate:
-- Sellbird proposes, the user confirms, and only confirmed signals are
-- collected. observations.signal_code must name a code in it: SQLite enforces
-- that with a trigger, Postgres with this foreign key, so an unknown code is
-- refused on both and nothing is stored. ON DELETE RESTRICT keeps facts from
-- pointing at a code that no longer exists.

CREATE TABLE signal_codes (
    code text COLLATE "C" PRIMARY KEY,
    label text COLLATE "C" DEFAULT '',
    description text COLLATE "C" DEFAULT '',
    category text COLLATE "C" DEFAULT '',
    value_type text COLLATE "C" DEFAULT 'text',
    collector text COLLATE "C" DEFAULT '',
    cost_note text COLLATE "C" DEFAULT '',
    status text COLLATE "C" DEFAULT 'proposed',
    confidence_floor double precision DEFAULT 0.0,
    created_at text COLLATE "C" DEFAULT sb_now(),
    updated_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
COMMENT ON TABLE signal_codes IS
    'Governed signal vocabulary. Only status = confirmed signals are collected; only a human confirms.';

CREATE TABLE observations (
    id text COLLATE "C" PRIMARY KEY,
    company_id text COLLATE "C" DEFAULT '',
    prospect_id text COLLATE "C" DEFAULT '',
    signal_code text COLLATE "C" NOT NULL,
    collector text COLLATE "C" DEFAULT '',
    value_num double precision,
    value_text text COLLATE "C" DEFAULT '',
    confidence double precision DEFAULT 1.0,
    evidence_url text COLLATE "C" DEFAULT '',
    observed_at text COLLATE "C" DEFAULT sb_now(),
    run_id text COLLATE "C" DEFAULT '',
    rowid bigint GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT observations_signal_code_fkey FOREIGN KEY (signal_code)
        REFERENCES signal_codes (code) ON UPDATE RESTRICT ON DELETE RESTRICT
);
COMMENT ON TABLE observations IS
    'One row per fact, with its confidence and provenance. Re-observing is a time series.';
CREATE INDEX idx_obs_company ON observations (company_id);
CREATE INDEX idx_obs_signal ON observations (signal_code);
CREATE INDEX idx_obs_company_signal ON observations (company_id, signal_code, observed_at);
CREATE INDEX idx_obs_run ON observations (run_id);
CREATE INDEX idx_obs_rowid ON observations (rowid);
