-- Companies, contacts, campaigns, conversations, the action log, usage
-- accounting, the email-pattern cache, settings and the run log: the SQLite
-- schema as of its migration 16, column for column.
--
-- Conventions for every Sellbird table on Postgres:
-- - text is COLLATE "C" (byte order, as SQLite's BINARY), so text timestamps,
--   ORDER BY and LIKE behave exactly as on SQLite.
-- - Timestamps are ISO-8601 text defaulting to sb_now() (SQLite's
--   CURRENT_TIMESTAMP), so values move between backends unchanged.
-- - SQLite INTEGER is bigint, REAL is double precision.
-- - Each table ends with a hidden `rowid` identity: SQLite's rowid, used as an
--   insertion-order tie-break. Results omit it unless a query selects it.
-- - No foreign keys between these tables: SQLite never enforced them (several
--   id columns default to '' rather than NULL). The one enforced reference is
--   the governed signal vocabulary (migration 0003).

CREATE TABLE companies (
    id text COLLATE "C" PRIMARY KEY,
    name text COLLATE "C" DEFAULT '',
    domain text COLLATE "C" DEFAULT '',
    website text COLLATE "C" DEFAULT '',
    description text COLLATE "C" DEFAULT '',
    industry text COLLATE "C" DEFAULT '',
    company_size text COLLATE "C" DEFAULT '',
    location text COLLATE "C" DEFAULT '',
    source text COLLATE "C" DEFAULT '',
    source_url text COLLATE "C" DEFAULT '',
    notes text COLLATE "C" DEFAULT '',
    created_at text COLLATE "C" DEFAULT sb_now(),
    updated_at text COLLATE "C" DEFAULT sb_now(),
    tech_stack_json text COLLATE "C" DEFAULT '[]',
    signals_json text COLLATE "C" DEFAULT '[]',
    external_id text COLLATE "C" DEFAULT '',
    phone text COLLATE "C" DEFAULT '',
    prospects_checked_at text COLLATE "C" DEFAULT NULL,
    profile_checked_at text COLLATE "C" DEFAULT NULL,
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_companies_domain ON companies (domain);
CREATE UNIQUE INDEX uq_companies_domain ON companies (domain) WHERE domain <> '';
CREATE UNIQUE INDEX uq_companies_external ON companies (external_id) WHERE external_id <> '';

CREATE TABLE prospects (
    id text COLLATE "C" PRIMARY KEY,
    company_id text COLLATE "C" DEFAULT '',
    first_name text COLLATE "C" DEFAULT '',
    last_name text COLLATE "C" DEFAULT '',
    email text COLLATE "C" DEFAULT '',
    email_verified bigint DEFAULT 0,
    phone text COLLATE "C" DEFAULT '',
    phone_verified bigint DEFAULT 0,
    linkedin_url text COLLATE "C" DEFAULT '',
    title text COLLATE "C" DEFAULT '',
    seniority text COLLATE "C" DEFAULT '',
    department text COLLATE "C" DEFAULT '',
    source text COLLATE "C" DEFAULT '',
    source_url text COLLATE "C" DEFAULT '',
    status text COLLATE "C" DEFAULT 'new',
    score bigint DEFAULT 0,
    personalization_notes text COLLATE "C" DEFAULT '',
    company text COLLATE "C" DEFAULT '',
    industry text COLLATE "C" DEFAULT '',
    company_size text COLLATE "C" DEFAULT '',
    created_at text COLLATE "C" DEFAULT sb_now(),
    updated_at text COLLATE "C" DEFAULT sb_now(),
    email_status text COLLATE "C" DEFAULT '',
    timezone text COLLATE "C" DEFAULT '',
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_prospects_company_id ON prospects (company_id);
CREATE INDEX idx_prospects_status ON prospects (status);
CREATE INDEX idx_prospects_email ON prospects (email);
CREATE UNIQUE INDEX uq_prospects_email ON prospects (email) WHERE email <> '';
CREATE UNIQUE INDEX uq_prospects_linkedin ON prospects (linkedin_url) WHERE linkedin_url <> '';
CREATE INDEX idx_prospects_name_company
    ON prospects (lower(first_name), lower(last_name), lower(company));
CREATE INDEX idx_prospects_status_updated ON prospects (status, updated_at);

CREATE TABLE campaigns (
    id text COLLATE "C" PRIMARY KEY,
    name text COLLATE "C" DEFAULT '',
    channel text COLLATE "C" DEFAULT 'email',
    instantly_campaign_id text COLLATE "C" DEFAULT '',
    sequence_json text COLLATE "C" DEFAULT '[]',
    prospect_ids_json text COLLATE "C" DEFAULT '[]',
    status text COLLATE "C" DEFAULT 'draft',
    created_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_campaigns_status ON campaigns (status);

CREATE TABLE conversations (
    id text COLLATE "C" PRIMARY KEY,
    prospect_id text COLLATE "C",
    campaign_id text COLLATE "C" DEFAULT '',
    channel text COLLATE "C" DEFAULT 'email',
    thread_json text COLLATE "C" DEFAULT '[]',
    intent text COLLATE "C" DEFAULT '',
    stage text COLLATE "C" DEFAULT 'initial_outreach',
    status text COLLATE "C" DEFAULT 'open',
    created_at text COLLATE "C" DEFAULT sb_now(),
    updated_at text COLLATE "C" DEFAULT sb_now(),
    mailbox_id text COLLATE "C" DEFAULT '',
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_conversations_status ON conversations (status);
CREATE INDEX idx_conversations_campaign_id ON conversations (campaign_id);
CREATE INDEX idx_conversations_prospect_id ON conversations (prospect_id);
CREATE INDEX idx_conversations_intent ON conversations (intent);

CREATE TABLE actions (
    id text COLLATE "C" PRIMARY KEY,
    action_type text COLLATE "C",
    agent text COLLATE "C",
    details_json text COLLATE "C" DEFAULT '{}',
    created_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_actions_created_at ON actions (created_at);
CREATE INDEX idx_actions_type_created ON actions (action_type, created_at);

CREATE TABLE usage_log (
    id text COLLATE "C" PRIMARY KEY,
    date text COLLATE "C" UNIQUE,
    claude_calls bigint DEFAULT 0,
    usage_percent double precision DEFAULT 0.0,
    created_at text COLLATE "C" DEFAULT sb_now(),
    codex_calls bigint DEFAULT 0,
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE processed_replies (
    reply_id text COLLATE "C" PRIMARY KEY,
    processed_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE usage_events (
    id text COLLATE "C" PRIMARY KEY,
    created_at text COLLATE "C" DEFAULT sb_now(),
    agent text COLLATE "C" DEFAULT '',
    task text COLLATE "C" DEFAULT '',
    session_id text COLLATE "C" DEFAULT '',
    request_key text COLLATE "C" DEFAULT '',
    model text COLLATE "C" DEFAULT '',
    input_tokens bigint DEFAULT 0,
    output_tokens bigint DEFAULT 0,
    cache_read_tokens bigint DEFAULT 0,
    cache_creation_tokens bigint DEFAULT 0,
    cost_usd double precision DEFAULT 0.0,
    duration_ms bigint DEFAULT 0,
    num_turns bigint DEFAULT 0,
    is_error bigint DEFAULT 0,
    source text COLLATE "C" DEFAULT 'result_json',
    provider text COLLATE "C" DEFAULT 'claude',
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_usage_events_created ON usage_events (created_at);
CREATE INDEX idx_usage_events_agent ON usage_events (agent);
CREATE INDEX idx_usage_events_session ON usage_events (session_id);
CREATE INDEX idx_usage_events_provider ON usage_events (provider);
CREATE UNIQUE INDEX uq_usage_events_request ON usage_events (request_key) WHERE request_key <> '';

CREATE TABLE email_patterns (
    domain text COLLATE "C" PRIMARY KEY,
    pattern text COLLATE "C" DEFAULT '',
    source text COLLATE "C" DEFAULT '',
    confidence double precision DEFAULT 0.0,
    mx_type text COLLATE "C" DEFAULT '',
    is_catch_all bigint DEFAULT -1,
    updated_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE settings (
    key text COLLATE "C" PRIMARY KEY,
    value text COLLATE "C" DEFAULT '',
    updated_at text COLLATE "C" DEFAULT sb_now(),
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE runs (
    id text COLLATE "C" PRIMARY KEY,
    stage text COLLATE "C" DEFAULT '',
    status text COLLATE "C" DEFAULT 'running',
    provider text COLLATE "C" DEFAULT '',
    records bigint DEFAULT 0,
    cost_usd double precision DEFAULT 0.0,
    params_json text COLLATE "C" DEFAULT '{}',
    error text COLLATE "C" DEFAULT '',
    started_at text COLLATE "C" DEFAULT sb_now(),
    ended_at text COLLATE "C",
    rowid bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_runs_stage_started ON runs (stage, started_at);
